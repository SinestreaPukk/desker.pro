// Draws the decor atlas from the catalogue (packages/shared/src/decor.manifest.json) and writes the database seed.
//   node scripts/gen-decor-assets.ts
// Outputs: apps/village/public/assets/decor/decor.png + decor.json (atlas: frame names `<id>:<rotation>:<frame>`), db/migrations/015_village_decor.sql.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { Canvas } from './png.ts'
import { painter } from './world-art.ts'
import { PAINT } from './decor-art.ts'

const items = JSON.parse(readFileSync(new URL('../packages/shared/src/decor.manifest.json', import.meta.url), 'utf8')).items as any[]
const out = new URL('../apps/village/public/assets/decor/', import.meta.url).pathname
mkdirSync(out, { recursive: true })

const missing = items.filter((i) => !PAINT[i.id]).map((i) => i.id), extra = Object.keys(PAINT).filter((k) => !items.some((i) => i.id === k))
if (missing.length || extra.length) throw new Error(`painters and catalogue disagree. No art: ${missing}. No catalogue entry: ${extra}`)

/** Quarter turn clockwise of a w x h pixel box. */
const turn = (cv: Canvas): Canvas => { const r = new Canvas(cv.h, cv.w); for (let y = 0; y < cv.h; y++) for (let x = 0; x < cv.w; x++) r.data.set(cv.data.subarray((y * cv.w + x) * 4, (y * cv.w + x) * 4 + 4), (x * r.w + (cv.h - 1 - y)) * 4); return r }

interface Cell { name: string; cv: Canvas }
const cells: Cell[] = []
for (const it of items) for (let f = 0; f < it.frames; f++) {
  let cv = new Canvas(it.w * 16, it.h * 16); PAINT[it.id](painter(cv, 0, 0), f, it.w, it.h)
  for (let q = 0; q < 4; q++) { // q quarter turns = rotation q*90
    if (it.rot.includes(q * 90)) cells.push({ name: `${it.id}:${q * 90}:${f}`, cv })
    cv = turn(cv)
  }
}
// shelf-pack, 1 px of transparent padding around every frame, 512 px wide
const W = 512, frames: Record<string, unknown> = {}
let x = 1, y = 1, rowH = 0
const placed = cells.map((c) => { if (x + c.cv.w + 1 > W) { x = 1; y += rowH + 1; rowH = 0 } const p = { c, x, y }; x += c.cv.w + 1; rowH = Math.max(rowH, c.cv.h); return p })
const atlas = new Canvas(W, y + rowH + 1)
for (const { c, x, y } of placed) { atlas.data.forEach; for (let j = 0; j < c.cv.h; j++) atlas.data.set(c.cv.data.subarray(j * c.cv.w * 4, (j + 1) * c.cv.w * 4), ((y + j) * atlas.w + x) * 4); frames[c.name] = { frame: { x, y, w: c.cv.w, h: c.cv.h }, sourceSize: { w: c.cv.w, h: c.cv.h }, spriteSourceSize: { x: 0, y: 0, w: c.cv.w, h: c.cv.h } } }
writeFileSync(out + 'decor.png', atlas.toPng())
writeFileSync(out + 'decor.json', JSON.stringify({ frames, meta: { image: 'decor.png', size: { w: atlas.w, h: atlas.h }, scale: '1', note: 'Placeholder art from scripts/gen-decor-assets.ts. An artist replaces decor.png and keeps the frame names and sizes.' } }))

// the database seed: the catalogue is the source, this only copies it (safe to run again)
const q = (s: string | null) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`)
const j = (o: unknown) => q(JSON.stringify(o))
writeFileSync(new URL('../db/migrations/015_village_decor.sql', import.meta.url).pathname, `-- Village Phase 2, checkpoint 2: the decor catalogue as rows. GENERATED by scripts/gen-decor-assets.ts from packages/shared/src/decor.manifest.json; do not edit by hand.
-- File only: apply by hand in the Neon SQL editor. Safe to run again (updates in place).
create table if not exists village_decor_item (
  id text primary key,
  name jsonb not null,            -- {en, th}
  category text not null,
  size_w int not null, size_h int not null,
  walkable boolean not null,
  layer text not null,
  rotations jsonb not null,
  sit_spots jsonb,
  interact text not null default 'none',
  price_leaves int not null,
  season text,
  pack text
);
${items.map((i) => `insert into village_decor_item (id, name, category, size_w, size_h, walkable, layer, rotations, sit_spots, interact, price_leaves, season) values (${q(i.id)}, ${j(i.name)}, ${q(i.cat)}, ${i.w}, ${i.h}, ${i.walkable}, ${q(i.layer)}, ${j(i.rot)}, ${i.sit ? j(i.sit) : 'null'}, ${q(i.interact)}, ${i.price}, ${q(i.season)})
  on conflict (id) do update set name = excluded.name, category = excluded.category, size_w = excluded.size_w, size_h = excluded.size_h, walkable = excluded.walkable, layer = excluded.layer, rotations = excluded.rotations, sit_spots = excluded.sit_spots, interact = excluded.interact, price_leaves = excluded.price_leaves, season = excluded.season;`).join('\n')}
`)
console.log(`${items.length} items, ${cells.length} frames, atlas ${atlas.w}x${atlas.h}`)
