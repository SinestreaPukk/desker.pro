#!/usr/bin/env python3
"""av-scene: the same shimaenaga as av-main, minus the UI branch, so it can perch on a post in the scene.
Rows 17-20 lose the branch, its snow tip and its shade; body, feet, tail and the blink stay byte-identical."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
src = (ROOT / 'art/sprites/av-main.sprite.txt').read_text().splitlines()
out, row, frame_start = [], -1, 0
for ln in src:
    if ln.startswith('# av-main'):
        ln = '# av-scene: av-main without the branch (perches on a post). Generated by art/authoring/gen_avatar_scene.py.'
    if ln.startswith('frame '):
        row = 0; out.append(ln); continue
    if row >= 0 and len(ln) == 24 and not ln.startswith(('#', 'size')):
        r = list(ln)
        if row == 17: r[0:6] = '.' * 6
        if row == 18: r[0:6] = '.' * 6
        if row == 19: r = ['.' if c == 'B' else c for c in r]
        if row == 20: r[0:18] = '.' * 18
        ln = ''.join(r); row += 1
    out.append(ln)
(ROOT / 'art/sprites/av-scene.sprite.txt').write_text('\n'.join(out) + '\n')
print('wrote av-scene')
