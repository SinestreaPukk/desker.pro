#!/usr/bin/env python3
"""Weather icons (16x16, yuki16, 4 colours each) for the Today greeting: sun, cloud, rain, snow, storm. Writes art/sprites/i-w-*.sprite.txt."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
def grid(): return [['.'] * 16 for _ in range(16)]
def disc(g, cx, cy, r, ch):
    for y in range(16):
        for x in range(16):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r: g[y][x] = ch
def outline(g, ch='K'):
    """1px outline around every filled cell (4-neighbour), on empty cells only."""
    edge = [(y, x) for y in range(16) for x in range(16) if g[y][x] == '.' and any(0 <= y + dy < 16 and 0 <= x + dx < 16 and g[y + dy][x + dx] not in '.' for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)))]
    for y, x in edge: g[y][x] = ch
def cloud(g, dy, fill, shade):
    for cx, cy, r in ((4.5, 8.5, 2.8), (8.5, 6.5, 3.6), (11.5, 9, 2.8)): disc_at(g, cx, cy + dy, r, fill)
    for y in range(9 + dy, 12 + dy):
        for x in range(3, 14): g[y][x] = fill
    for x in range(3, 14): g[11 + dy][x] = shade
    for x in range(8, 14): g[10 + dy][x] = shade
def disc_at(g, cx, cy, r, ch):
    for y in range(16):
        for x in range(16):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r: g[y][x] = ch
def put(g, pts, ch):
    for x, y in pts:
        if 0 <= y < 16: g[y][x] = ch
def sun():
    g = grid(); disc(g, 7.5, 7.5, 3.6, 'a'); put(g, [(6, 5), (7, 5), (6, 6)], 'b'); outline(g)
    for x, y in ((7, 0), (8, 0), (7, 1), (8, 1), (7, 14), (8, 14), (7, 15), (8, 15), (0, 7), (0, 8), (1, 7), (1, 8), (14, 7), (14, 8), (15, 7), (15, 8),
                 (2, 2), (3, 3), (12, 3), (13, 2), (2, 13), (3, 12), (12, 12), (13, 13)): g[y][x] = 'K'
    return g
def cld(fill='w', shade='s', dy=0, up=0):
    g = grid(); cloud(g, dy - up, fill, shade); outline(g); return g
def rain():
    g = cld(up=2)
    put(g, [(4, 12), (4, 13), (8, 13), (8, 14), (12, 12), (12, 13), (6, 15), (10, 15)], 'k'); return g
def snow():
    g = cld(up=2)
    put(g, [(4, 12), (3, 13), (5, 13), (4, 14), (8, 13), (7, 14), (9, 14), (8, 15), (12, 12), (11, 13), (13, 13), (12, 14)], 'k'); return g
def storm():
    g = cld('a', 'b', up=2)
    put(g, [(9, 11), (8, 12), (7, 13), (8, 13), (9, 13), (7, 14), (6, 15)], 'k'); return g
ICONS = {'sun': (sun(), {'K': 'yoru-2', 'a': 'hada-1', 'b': 'hada-0'}), 'cloud': (cld(), {'K': 'yoru-2', 'w': 'yuki-1', 's': 'yuki-2'}),
         'rain': (rain(), {'K': 'yoru-2', 'w': 'yuki-1', 's': 'yuki-2', 'k': 'kori-2'}), 'snow': (snow(), {'K': 'yoru-2', 'w': 'yuki-1', 's': 'yuki-2', 'k': 'kori-2'}),
         'storm': (storm(), {'K': 'yoru-2', 'a': 'yuki-3', 'b': 'yoru-0', 'k': 'beni'})}
if __name__ == '__main__':
    for name, (g, pal) in ICONS.items():
        used = [ch for ch in pal if any(ch in r for r in g)]
        txt = [f'# Icon: weather {name}. Generated by art/authoring/gen_weather.py.', 'size 16 16', 'palette yuki16', '. transparent'] + [f'{ch} {pal[ch]}' for ch in used] + ['frame rest'] + [''.join(r) for r in g]
        (ROOT / f'art/sprites/i-w-{name}.sprite.txt').write_text('\n'.join(txt) + '\n')
    print('wrote weather icons')
