"""Authoring aid: writes the committed art/sprites/*.sprite.txt grids.

Sprites are drawn as explicit pixel grids here (helpers only place palette letters; nothing is
resampled or generated by a model). The .sprite.txt files it writes are the source of truth,
so re-run this only when you change a drawing: python3 art/authoring/gen_sprites.py
"""
import pathlib
OUT = pathlib.Path(__file__).resolve().parent.parent / 'sprites'
OUT.mkdir(exist_ok=True)

def write(name, w, h, legend, frames, note=''):
    lines = [f'# {note}'] if note else []
    lines += [f'size {w} {h}', 'palette yuki16', '. transparent'] + [f'{k} {v}' for k, v in legend.items()]
    for fname, rows in frames:
        assert len(rows) == h, (name, fname, len(rows))
        for r in rows:
            assert len(r) == w, (name, fname, r, len(r))
        lines.append(f'frame {fname}')
        lines += rows
    (OUT / f'{name}.sprite.txt').write_text('\n'.join(lines) + '\n')

