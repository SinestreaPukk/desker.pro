# ---------------------------------------------------------------- avatars (24x24, idle + blink)
HEAD = {7: (5, 18), 8: (4, 19), 9: (3, 20), 10: (3, 20), 11: (3, 20), 12: (3, 20), 13: (3, 20), 14: (3, 20), 15: (4, 19), 16: (5, 18)}
BODY = {17: (6, 17), 18: (6, 17), 19: (6, 17), 20: (6, 17), 21: (5, 18)}

class Canvas:
    def __init__(self):
        self.g = [['.'] * 24 for _ in range(24)]
    def put(self, x, y, c): self.g[y][x] = c
    def row(self, y, x0, s):
        for i, c in enumerate(s):
            if c != ' ': self.g[y][x0 + i] = c
    def shape(self, spans, letters, outline='K', top=None, bottom=None):
        L = letters
        for y, (x0, x1) in spans.items():
            for x in range(x0, x1 + 1):
                edge = x in (x0, x1) or (top != -1 and y == (top if top is not None else min(spans))) or y == (bottom if bottom is not None else max(spans))
                if edge: self.g[y][x] = outline; continue
                t = (1 if x >= x1 - 2 else 0) + (1 if y >= max(spans) - 2 else 0) + (1 if y >= max(spans) - 1 else 0)
                self.g[y][x] = L[min(t, 3)]
    def rows(self): return [''.join(r) for r in self.g]

def avatar(name, legend, build, note, variants=None):
    frames = []
    for blink in (False, True):
        c = Canvas(); build(c, blink); frames.append(('blink' if blink else 'idle-0', c.rows()))
    write(name, 24, 24, {'K': 'yoru-2', **legend}, frames, note)

def eyes(c, blink, ch='K', xs=(7, 15)):
    for x in xs:
        if not blink: c.put(x, 11, ch); c.put(x + 1, 11, ch)
        c.put(x, 12, 'K' if blink else ch); c.put(x + 1, 12, 'K' if blink else ch)

def body_feet(c, letters):
    c.shape(BODY, letters, top=-1)  # the head's bottom outline is the body's top: no double line
    for x in range(5, 19): c.put(x, 21, 'K')

