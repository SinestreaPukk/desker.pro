# ---------------------------------------------------------------- icons (16x16, <=4 colours, 1px yoru-2 outline)
def icon(name, rows, legend):
    rows = [r.ljust(16, '.') for r in rows]
    pad = 16 - len(rows)
    rows = ['.' * 16] * (pad // 2) + rows + ['.' * 16] * (pad - pad // 2)
    write(name, 16, 16, {'K': 'yoru-2', **legend}, [('rest', rows)], f'Icon: {name}.')

